// Generate the narration with ElevenLabs, one clip per beat, and write the timing the edit follows.
// Usage: node tools/voice.mjs [--voice <voice id>] [--only id1,id2]
// Needs ELEVENLABS_API_KEY in the environment (behind a proxy, run node with NODE_USE_ENV_PROXY=1). Clips are cached in audio/vo/ by a hash of their text.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { CHAPTERS } from '../content/script.js';
import { parseArgs } from './browser.mjs';

const o = parseArgs({ voice: 'mBuVX55i5Lt3LEkHr36R', model: 'eleven_multilingual_v2', only: '', lead: 3, card: 3.6, speed: 0.93, pause: 0.8 });
const KEY = process.env.ELEVENLABS_API_KEY ?? 'proxy-injected';
const DIR = 'audio/vo';
fs.mkdirSync(DIR, { recursive: true });

const beats = CHAPTERS.flatMap((c) => c.beats);
const only = new Set(String(o.only).split(',').filter(Boolean));
const hashOf = (b) => crypto.createHash('sha1').update(`${o.voice}|${o.model}|${o.speed}|${b.text}`).digest('hex').slice(0, 10);
const duration = (f) => Number(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f]).toString().trim());

async function synth(b, i) {
  const file = path.join(DIR, `${b.id}.mp3`), tag = path.join(DIR, `${b.id}.hash`);
  const fresh = fs.existsSync(file) && fs.existsSync(tag) && fs.readFileSync(tag, 'utf8') === hashOf(b);
  if (fresh && !only.has(b.id)) return;
  for (let attempt = 1; ; attempt++) {
    const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${o.voice}?output_format=mp3_44100_192`, {
      method: 'POST',
      headers: { 'content-type': 'application/json', 'xi-api-key': KEY },
      body: JSON.stringify({
        text: b.text, model_id: o.model,
        previous_text: beats[i - 1]?.text, next_text: beats[i + 1]?.text,
        voice_settings: { stability: 0.5, similarity_boost: 0.8, style: 0.12, use_speaker_boost: true, speed: o.speed },
      }),
    });
    if (res.ok) { fs.writeFileSync(file, Buffer.from(await res.arrayBuffer())); fs.writeFileSync(tag, hashOf(b)); console.log('voiced', b.id); return; }
    if (attempt >= 4) throw new Error(`${b.id}: HTTP ${res.status} ${await res.text()}`);
    await new Promise((r) => setTimeout(r, 2000 * attempt));
  }
}

// three at a time
const queue = beats.map((b, i) => [b, i]);
await Promise.all([0, 1, 2].map(async () => { for (let j; (j = queue.shift());) await synth(...j); }));

// timing: lead-in, a title card before each titled chapter, then beats back to back with their pauses
const timing = { beats: {}, chapters: {}, total: 0 };
let t = o.lead;
for (const c of CHAPTERS) {
  timing.chapters[c.id] = { start: +t.toFixed(3), title: c.title };
  if (c.title) t += o.card;
  for (const b of c.beats) {
    const dur = duration(path.join(DIR, `${b.id}.mp3`));
    timing.beats[b.id] = { start: +t.toFixed(3), dur: +dur.toFixed(3) };
    t += dur + (b.pause ?? o.pause) + (b.hold ?? 0);
  }
}
timing.total = +(t + 8).toFixed(3);   // room for the end card
fs.writeFileSync('content/timing.js', `// Generated by tools/voice.mjs from the recorded narration. Do not edit.\nexport const TIMING = ${JSON.stringify(timing, null, 1)};\n`);
console.log(`total ${(timing.total / 60).toFixed(2)} min, ${beats.length} beats`);
